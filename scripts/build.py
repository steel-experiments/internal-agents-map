#!/usr/bin/env python3
"""Build the Internal Agents Map.

Reads every ``data/agents/*.yaml`` and regenerates three artifacts:

  1. README.md  ........ landscape table (rewritten between the BEGIN/END markers)
  2. docs/landscape.md  full per-agent catalog
  3. data/agents.json  .. flat export for programmatic use

Usage::

    python scripts/build.py

The build is idempotent: re-running with unchanged data produces no diff.
Contributors add an agent by dropping a YAML in ``data/agents/`` and re-running this.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit(
        "PyYAML is required to build the map.\n"
        "  Install it once:  pip install pyyaml\n"
        "  Then re-run:      python scripts/build.py"
    )

ROOT = Path(__file__).resolve().parent.parent
AGENTS_DIR = ROOT / "data" / "agents"
README = ROOT / "README.md"
LANDSCAPE = ROOT / "docs" / "landscape.md"
DATA_JSON = ROOT / "data" / "agents.json"

BEGIN = "<!-- BEGIN LANDSCAPE -->"
END = "<!-- END LANDSCAPE -->"

# Required top-level fields. Optional fields can be omitted entirely.
REQUIRED = ["id", "company", "agent_name", "year", "status", "domains", "autonomy", "summary"]
AUTONOMY = {"assistive", "human-in-loop", "drafts-reviewed", "autonomous"}
STATUS = {"internal", "open-sourced", "commercialized"}

TABLE_HEADER = (
    "| Company | Agent | Domains | Autonomy | Sandbox | Interfaces | Status | Year |\n"
    "| --- | --- | --- | --- | --- | --- | --- | --- |"
)


def die(msg: str) -> "NoReturn":
    print(msg, file=sys.stderr)
    sys.exit(1)


def load_agents() -> list[dict]:
    files = sorted(AGENTS_DIR.glob("*.yaml"))
    if not files:
        die(f"No agent YAML files found in {AGENTS_DIR.relative_to(ROOT)}.")

    agents: list[dict] = []
    for f in files:
        try:
            data = yaml.safe_load(f.read_text(encoding="utf-8"))
        except yaml.YAMLError as e:
            die(f"YAML parse error in {f.name}:\n    {e}")

        if not isinstance(data, dict):
            die(f"{f.name}: top-level YAML must be a mapping (key: value).")

        missing = [k for k in REQUIRED if not data.get(k)]
        if missing:
            die(f"{f.name}: missing required field(s): {', '.join(missing)}")

        if data["id"] != f.stem:
            die(f"{f.name}: 'id' ({data['id']!r}) must match the filename stem ({f.stem!r}).")

        if data["autonomy"] not in AUTONOMY:
            die(f"{f.name}: autonomy {data['autonomy']!r} is invalid. "
                f"Use one of: {', '.join(sorted(AUTONOMY))}.")
        if data["status"] not in STATUS:
            die(f"{f.name}: status {data['status']!r} is invalid. "
                f"Use one of: {', '.join(sorted(STATUS))}.")

        if not isinstance(data["domains"], list):
            die(f"{f.name}: 'domains' must be a list.")

        agents.append(data)

    agents.sort(key=lambda a: (a["company"].lower(), a["agent_name"].lower()))
    return agents


def cell(value) -> str:
    """Render a value as a table cell (lists become comma-joined; empty -> em-dash)."""
    if value is None or value == "" or value == []:
        return "—"
    if isinstance(value, list):
        return ", ".join(str(v) for v in value)
    return str(value)


def render_table(agents: list[dict]) -> str:
    lines = [BEGIN, "", TABLE_HEADER]
    for a in agents:
        arch = a.get("architecture") or {}
        link = f"[{a['agent_name']}](data/agents/{a['id']}.yaml)"
        lines.append(
            "| {company} | {agent} | {domains} | {autonomy} | {sandbox} | {ifs} | {status} | {year} |".format(
                company=a["company"],
                agent=link,
                domains=cell(a["domains"]),
                autonomy=a["autonomy"],
                sandbox=cell(arch.get("sandbox")),
                ifs=cell(arch.get("interfaces")),
                status=a["status"],
                year=a["year"],
            )
        )
    lines += ["", END]
    return "\n".join(lines)


def render_landscape(agents: list[dict]) -> str:
    out = [
        "# Internal Agents — Full Catalog",
        "",
        "<!-- This file is GENERATED by scripts/build.py. Do not edit by hand. -->",
        "<!-- To add or change an entry, edit data/agents/*.yaml and re-run the build. -->",
        "",
        f"_{len(agents)} agents cataloged. Sorted alphabetically by company._",
        "",
    ]
    for a in agents:
        arch = a.get("architecture") or {}
        out.append(f"## {a['company']} — {a['agent_name']}")
        out.append("")
        summary = a.get("summary", "")
        if summary:
            out.append(f"> {summary}")
            out.append("")

        meta = [
            ("Year", a.get("year")),
            ("Status", a.get("status")),
            ("Domains", cell(a.get("domains"))),
            ("Autonomy", a.get("autonomy")),
            ("Headline metric", a.get("headline_metric")),
        ]
        out.append("| | |")
        out.append("| --- | --- |")
        for label, val in meta:
            if val not in (None, "", []):
                out.append(f"| **{label}** | {val} |")
        out.append("")

        if arch:
            out.append("**Architecture**")
            out.append("")
            for key in ("sandbox", "harness", "model", "tool_access", "interfaces",
                        "knowledge", "credentials", "context_mgmt"):
                val = arch.get(key)
                if val:
                    out.append(f"- **{key.replace('_', ' ').title()}:** {val}")
            out.append("")

        primitives = a.get("primitives")
        if primitives:
            out.append("**Primitives**")
            out.append("")
            for p in primitives:
                name = p.get("name", "") if isinstance(p, dict) else str(p)
                desc = p.get("desc", "") if isinstance(p, dict) else ""
                out.append(f"- **{name}** — {desc}" if desc else f"- {name}")
            out.append("")

        metrics = a.get("key_metrics")
        if metrics:
            out.append("**Key metrics**")
            out.append("")
            for m in metrics:
                out.append(f"- {m}")
            out.append("")

        lessons = a.get("lessons_learned")
        if lessons:
            out.append("**Lessons learned**")
            out.append("")
            for l in lessons:
                out.append(f"- {l}")
            out.append("")

        sources = a.get("sources")
        if sources:
            out.append("**Sources**")
            out.append("")
            for s in sources:
                title = s.get("title", s.get("url", ""))
                url = s.get("url", "")
                stype = s.get("type", "")
                tail = f" _({stype})_" if stype else ""
                out.append(f"- [{title}]({url}){tail}")
            out.append("")

        out.append("---")
        out.append("")
    return "\n".join(out)


def replace_between_markers(text: str, block: str) -> str:
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1:
        die(f"README.md is missing the '{BEGIN}' / '{END}' markers.\n"
            "Restore them from the repo template before building.")
    return text[:start] + block + text[end + len(END):]


def main() -> None:
    agents = load_agents()

    readme_old = README.read_text(encoding="utf-8")
    readme_new = replace_between_markers(readme_old, render_table(agents))
    if readme_new != readme_old:
        README.write_text(readme_new, encoding="utf-8")
        print(f"updated {README.relative_to(ROOT)}")
    else:
        print(f"unchanged {README.relative_to(ROOT)}")

    LANDSCAPE.parent.mkdir(parents=True, exist_ok=True)
    LANDSCAPE.write_text(render_landscape(agents), encoding="utf-8")
    print(f"wrote {LANDSCAPE.relative_to(ROOT)}")

    DATA_JSON.write_text(
        json.dumps(agents, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"wrote {DATA_JSON.relative_to(ROOT)}")

    print(f"\n{len(agents)} agents. Build complete.")


if __name__ == "__main__":
    main()
